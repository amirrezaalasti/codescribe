#!/usr/bin/env node
/**
 * Generate CATALOG.md from all skill frontmatter under skills/.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SKILLS_DIR = path.join(ROOT, "skills");
const OUT = path.join(ROOT, "CATALOG.md");

function walkSkillDirs(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const full = path.join(dir, entry.name);
    const skillMd = path.join(full, "SKILL.md");
    if (fs.existsSync(skillMd)) {
      acc.push({ dir: full, folder: entry.name, skillMd });
    } else {
      walkSkillDirs(full, acc);
    }
  }
  return acc;
}

function parseFrontmatter(content) {
  if (!content.startsWith("---")) return {};
  const end = content.indexOf("\n---", 4);
  if (end === -1) return {};
  const yaml = content.slice(4, end).trim();
  const data = {};
  let currentKey = null;
  let multiBuf = [];
  let multiline = false;

  const flush = () => {
    if (currentKey && multiline) {
      data[currentKey] = multiBuf.join(" ").trim();
      multiline = false;
      multiBuf = [];
      currentKey = null;
    }
  };

  for (const line of yaml.split(/\r?\n/)) {
    if (multiline) {
      if (/^\s+/.test(line) || line.trim() === "") {
        multiBuf.push(line.trim());
        continue;
      }
      flush();
    }
    const m = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!m) continue;
    const [, key, rest] = m;
    if (rest === "" || /^[>|][+-]?$/.test(rest)) {
      currentKey = key;
      multiline = true;
      multiBuf = [];
      continue;
    }
    data[key] = rest.replace(/^["']|["']$/g, "").trim();
  }
  flush();
  return data;
}

function categoryOf(skillDir) {
  const rel = path.relative(SKILLS_DIR, skillDir);
  const parts = rel.split(path.sep);
  return parts.length > 1 ? parts[0] : "root";
}

function main() {
  const skills = walkSkillDirs(SKILLS_DIR).map((s) => {
    const content = fs.readFileSync(s.skillMd, "utf8");
    const data = parseFrontmatter(content);
    const rel = path.relative(ROOT, s.dir).split(path.sep).join("/");
    return {
      name: data.name || s.folder,
      description: data.description || "",
      category: categoryOf(s.dir),
      path: rel,
    };
  });

  skills.sort((a, b) => {
    if (a.category !== b.category) return a.category.localeCompare(b.category);
    return a.name.localeCompare(b.name);
  });

  const byCat = new Map();
  for (const s of skills) {
    if (!byCat.has(s.category)) byCat.set(s.category, []);
    byCat.get(s.category).push(s);
  }

  const lines = [
    "<!-- AUTO-GENERATED by scripts/generate-catalog.mjs — do not edit by hand -->",
    "",
    "# Skill Catalog",
    "",
    `Generated from ${skills.length} skills. Install: \`npx skills add amirrezaalasti/codescribe\``,
    "",
  ];

  for (const [cat, list] of byCat) {
    lines.push(`## ${cat}`, "");
    lines.push("| Skill | Description | Path |");
    lines.push("| --- | --- | --- |");
    for (const s of list) {
      const desc = s.description.replace(/\|/g, "\\|");
      lines.push(`| \`${s.name}\` | ${desc} | [\`${s.path}\`](${s.path}) |`);
    }
    lines.push("");
  }

  fs.writeFileSync(OUT, lines.join("\n") + "\n", "utf8");
  console.log(`Wrote ${OUT} (${skills.length} skills)`);
}

main();
